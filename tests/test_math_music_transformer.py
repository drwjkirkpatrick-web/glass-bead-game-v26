class TestBidirectionalTransformations:
    """Test music→math direction."""

    def test_music_to_math_fugue(self):
        t = MathMusicTransformer()
        result = t.transform(
            origin_concept="Fugue subject",
            origin_domain="Music",
            destination_domain="Mathematics",
            structural_property="recursive self-referential melodic statement",
        )
        assert result.direction == "music→math"
        assert len(result.steps) == 6
        assert result.total_confidence >= 0.3

    def test_music_to_math_overtone(self):
        t = MathMusicTransformer()
        result = t.transform(
            origin_concept="Overtone series",
            origin_domain="Music",
            destination_domain="Mathematics",
            structural_property="harmonic frequencies as integer multiples",
        )
        assert result.direction == "music→math"
        assert "fourier" in result.isomorphisms[0].lower() or "eigen" in result.isomorphisms[0].lower()

    def test_round_trip_fidelity(self):
        """math→music→language→math round-trip should preserve concept identity."""
        t = MathMusicTransformer()
        result1 = t.transform(
            origin_concept="Cyclic group Z_12",
            origin_domain="Mathematics",
            destination_domain="Music",
            structural_property="cyclic group generated by coprime element",
        )
        # The destination concept should contain musical terminology
        assert any(word in result1.destination_concept.lower() for word in
                    ["fifth", "circle", "tonic", "scale", "harmonic", "interval", "octave"])


