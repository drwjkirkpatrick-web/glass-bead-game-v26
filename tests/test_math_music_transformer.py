class TestBatchTransform:
    """Test batch processing."""

    def test_batch_transform(self):
        t = MathMusicTransformer()
        moves = [
            {"from_concept": "Group", "from_domain": "Mathematics", "to_domain": "Music", "structural_property": "closure"},
            {"from_concept": "Fugue", "from_domain": "Music", "to_domain": "Mathematics", "structural_property": "recursion"},
        ]
        results = t.batch_transform(moves)
        assert len(results) == 2
        assert results[0].direction == "math→music"
        assert results[1].direction == "music→math"


