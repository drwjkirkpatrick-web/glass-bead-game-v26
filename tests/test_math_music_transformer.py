class TestCoreIsomorphisms:
    """Test the 10 core isomorphisms from the library."""

    def test_cyclic_group_circle_of_fifths(self):
        t = MathMusicTransformer()
        result = t.transform(
            origin_concept="Cyclic group Z_12",
            origin_domain="Mathematics",
            destination_domain="Music",
            structural_property="cyclic group generated by coprime element",
        )
        assert result.direction == "math→music"
        assert "cyclic" in result.isomorphisms[0].lower()
        assert result.total_confidence >= 0.3
        assert result.total_confidence <= 0.99
        assert len(result.steps) == 6
