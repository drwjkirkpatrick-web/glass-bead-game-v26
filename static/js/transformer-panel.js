/**
 * Math ↔ Music Transformer Dashboard Panel
 * Real-time visualization of bidirectional transformation with token stream.
 */

(function() {
    'use strict';

    const TransformerPanel = {
        container: null,
        tokenDisplay: null,
        stageBar: null,
        confidenceGauge: null,
        catalogList: null,
        isRunning: false,
        currentTokens: [],
        maxVisibleTokens: 12,
        tokenFadeDelay: 3000,

        init(containerId) {
            this.container = document.getElementById(containerId);
            if (!this.container) {
                console.warn('TransformerPanel: container not found:', containerId);
                return;
            }
            this._buildUI();
            this._bindEvents();
            this._loadCatalog();
        },

        _buildUI() {
            this.container.innerHTML = `
                <div class="transformer-header">
                    <span class="transformer-title">MATH ↔ MUSIC</span>
                    <span class="transformer-subtitle">Twin Grammar Transformer</span>
                    <span class="transformer-status" id="transformer-status">IDLE</span>
                </div>

                <!-- Direction selector -->
                <div class="transformer-direction">
                    <label>Direction</label>
                    <div class="direction-toggle">
                        <button class="dir-btn active" data-dir="math→music">Math → Music</button>
                        <button class="dir-btn" data-dir="music→math">Music → Math</button>
                    </div>
                </div>

                <!-- Input fields -->
                <div class="transformer-inputs">
                    <div class="input-row">
                        <label>Origin Concept</label>
                        <input type="text" id="transformer-origin" placeholder="e.g., Fourier Transform" value="Cyclic group Z_12">
                    </div>
                    <div class="input-row">
                        <label>Structural Property</label>
                        <input type="text" id="transformer-property" placeholder="e.g., decomposition into harmonics" value="cyclic group generated by coprime element">
                    </div>
                    <div class="input-row">
                        <label>Resonance (optional)</label>
                        <textarea id="transformer-resonance" rows="2" placeholder="A single luminous sentence..."></textarea>
                    </div>
                </div>

                <!-- Run button -->
                <button class="transformer-run-btn" id="transformer-run">
                    <span class="run-icon">⟲</span> Transform
                </button>

                <!-- Stage progress bar -->
                <div class="transformer-stages">
                    <div class="stage-track">
                        <div class="stage-node" data-stage="PARSE">PARSE</div>
                        <div class="stage-line"></div>
                        <div class="stage-node" data-stage="TAG">TAG</div>
                        <div class="stage-line"></div>
                        <div class="stage-node" data-stage="MAP">MAP</div>
                        <div class="stage-line"></div>
                        <div class="stage-node" data-stage="PROJECT">PROJECT</div>
                        <div class="stage-line"></div>
                        <div class="stage-node" data-stage="COMPOSE">COMPOSE</div>
                        <div class="stage-line"></div>
                        <div class="stage-node" data-stage="VERIFY">VERIFY</div>
                    </div>
                </div>

                <!-- Token visualization -->
                <div class="transformer-tokens">
                    <label>Token Stream</label>
                    <div class="token-display" id="token-display"></div>
                </div>

                <!-- Confidence gauge -->
                <div class="transformer-confidence">
                    <label>Confidence</label>
                    <div class="confidence-track">
                        <div class="confidence-fill" id="confidence-fill" style="width: 0%"></div>
                    </div>
                    <span class="confidence-value" id="confidence-value">0.00</span>
                </div>

                <!-- Result area -->
                <div class="transformer-result" id="transformer-result" style="display: none;">
                    <div class="result-section">
                        <label>Destination</label>
                        <div class="result-text" id="result-destination"></div>
                    </div>
                    <div class="result-section">
                        <label>Resonance</label>
                        <div class="result-text resonance" id="result-resonance"></div>
                    </div>
                    <div class="result-section">
                        <label>Isomorphism</label>
                        <div class="result-text" id="result-isomorphism"></div>
                    </div>
                    <div class="result-section">
                        <label>Language Thread</label>
                        <div class="thread-list" id="result-thread"></div>
                    </div>
                </div>

                <!-- Isomorphism catalog -->
                <div class="transformer-catalog">
                    <label>Isomorphism Library</label>
                    <div class="catalog-list" id="catalog-list"></div>
                </div>
            `;

            this.tokenDisplay = this.container.querySelector('#token-display');
            this.stageBar = this.container.querySelector('.stage-track');
            this.confidenceGauge = this.container.querySelector('#confidence-fill');
            this.catalogList = this.container.querySelector('#catalog-list');
        },

        _bindEvents() {
            // Direction toggle
            this.container.querySelectorAll('.dir-btn').forEach(btn => {
                btn.addEventListener('click', () => {
                    this.container.querySelectorAll('.dir-btn').forEach(b => b.classList.remove('active'));
                    btn.classList.add('active');
                });
            });

            // Run button
            const runBtn = this.container.querySelector('#transformer-run');
            runBtn.addEventListener('click', () => this._runTransformation());
        },

        async _loadCatalog() {
            try {
                const response = await fetch('/api/transform/catalog');
                const catalog = await response.json();
                this._renderCatalog(catalog);
            } catch (err) {
                console.warn('Failed to load catalog:', err);
            }
        },

        _renderCatalog(catalog) {
            if (!this.catalogList) return;
            const items = Object.entries(catalog).map(([name, data]) => {
                const displayName = name.replace(/__/g, ' ↔ ').replace(/_/g, ' ');
                return `
                    <div class="catalog-item" data-iso="${name}">
                        <span class="catalog-name">${displayName}</span>
                        <span class="catalog-conf">${(data.confidence * 100).toFixed(0)}%</span>
                    </div>
                `;
            }).join('');
            this.catalogList.innerHTML = items;

            // Click to auto-fill
            this.catalogList.querySelectorAll('.catalog-item').forEach(item => {
                item.addEventListener('click', () => {
                    const isoName = item.dataset.iso;
                    const parts = isoName.split('__');
                    if (parts.length === 2) {
                        document.getElementById('transformer-origin').value = parts[0].replace(/_/g, ' ');
                        document.getElementById('transformer-property').value = 'structural correspondence';
                    }
                });
            });
        },

        async _runTransformation() {
            if (this.isRunning) return;
            this.isRunning = true;

            const origin = document.getElementById('transformer-origin').value.trim();
            const property = document.getElementById('transformer-property').value.trim();
            const resonance = document.getElementById('transformer-resonance').value.trim();
            const dirBtn = this.container.querySelector('.dir-btn.active');
            const direction = dirBtn ? dirBtn.dataset.dir : 'math→music';

            const originDomain = direction === 'math→music' ? 'Mathematics' : 'Music';
            const destDomain = direction === 'math→music' ? 'Music' : 'Mathematics';

            this._resetUI();
            this._setStatus('TRANSFORMING...');

            try {
                const response = await fetch('/api/transform', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({
                        origin_concept: origin,
                        origin_domain: originDomain,
                        destination_domain: destDomain,
                        structural_property: property,
                        resonance_sentence: resonance,
                        tokens: ['[INIT]', '[PARSE]', '[TAG]', '[MAP]', '[PROJECT]', '[COMPOSE]', '[VERIFY]'],
                    }),
                });

                const result = await response.json();
                await this._animateTransformation(result);
                this._showResult(result);
                this._setStatus('COMPLETE');
            } catch (err) {
                console.error('Transform failed:', err);
                this._setStatus('ERROR');
                this._showToken('⚠ transform failed', 'error');
            } finally {
                this.isRunning = false;
            }
        },

        _resetUI() {
            this.container.querySelectorAll('.stage-node').forEach(n => {
                n.classList.remove('active', 'complete');
            });
            if (this.confidenceGauge) {
                this.confidenceGauge.style.width = '0%';
            }
            document.getElementById('confidence-value').textContent = '0.00';
            if (this.tokenDisplay) this.tokenDisplay.innerHTML = '';
            document.getElementById('transformer-result').style.display = 'none';
        },

        _setStatus(status) {
            const el = document.getElementById('transformer-status');
            if (el) el.textContent = status;
        },

        async _animateTransformation(result) {
            const steps = result.steps || [];
            const totalTime = 2500; // ms for full animation
            const stepDelay = totalTime / Math.max(steps.length, 1);

            for (let i = 0; i < steps.length; i++) {
                const step = steps[i];
                await this._delay(stepDelay * 0.6);

                // Activate stage
                const node = this.container.querySelector(`.stage-node[data-stage="${step.stage}"]`);
                if (node) {
                    node.classList.add('active');
                    // Mark previous as complete
                    const allNodes = Array.from(this.container.querySelectorAll('.stage-node'));
                    const idx = allNodes.indexOf(node);
                    for (let j = 0; j < idx; j++) {
                        allNodes[j].classList.add('complete');
                        allNodes[j].classList.remove('active');
                    }
                }

                // Show token
                const tokenText = `[${step.stage}] ${step.language_thread.substring(0, 40)}...`;
                this._showToken(tokenText, 'step', step.confidence);

                await this._delay(stepDelay * 0.4);
            }

            // Final confidence
            if (this.confidenceGauge) {
                this.confidenceGauge.style.width = `${(result.total_confidence * 100).toFixed(0)}%`;
            }
            document.getElementById('confidence-value').textContent = result.total_confidence.toFixed(2);
        },

        _showToken(text, type, confidence) {
            if (!this.tokenDisplay) return;

            const token = document.createElement('div');
            token.className = `transformer-token token-${type}`;
            token.textContent = text;

            if (confidence !== undefined) {
                const intensity = Math.floor(confidence * 255);
                token.style.borderLeftColor = `rgb(0, ${intensity}, 255)`;
            }

            this.tokenDisplay.appendChild(token);
            this.currentTokens.push(token);

            // Animate in
            requestAnimationFrame(() => {
                token.style.opacity = '1';
                token.style.transform = 'translateX(0)';
            });

            // Limit visible tokens
            if (this.currentTokens.length > this.maxVisibleTokens) {
                const old = this.currentTokens.shift();
                if (old) {
                    old.style.opacity = '0';
                    setTimeout(() => old.remove(), 300);
                }
            }

            // Auto fade after delay
            setTimeout(() => {
                token.style.opacity = '0';
                setTimeout(() => {
                    if (token.parentNode) token.remove();
                }, 300);
            }, this.tokenFadeDelay);
        },

        _showResult(result) {
            const resultPanel = document.getElementById('transformer-result');
            if (!resultPanel) return;

            document.getElementById('result-destination').textContent =
                `${result.destination_concept} (${result.destination_domain})`;
            document.getElementById('result-resonance').textContent =
                result.resonance_sentence || 'No resonance generated.';
            document.getElementById('result-isomorphism').textContent =
                (result.isomorphisms || []).join(', ').replace(/__/g, ' ↔ ').replace(/_/g, ' ') || 'Generic homomorphism';

            const threadList = document.getElementById('result-thread');
            if (threadList && result.steps) {
                threadList.innerHTML = result.steps.map(s => `
                    <div class="thread-item">
                        <span class="thread-stage">${s.stage}</span>
                        <span class="thread-text">${s.language_thread}</span>
                    </div>
                `).join('');
            }

            resultPanel.style.display = 'block';
        },

        _delay(ms) {
            return new Promise(resolve => setTimeout(resolve, ms));
        },
    };

    // Export
    window.TransformerPanel = TransformerPanel;
})();
